inline uint32_t mix(uint32_t a, uint32_t b, uint32_t t /* 0..255 */) {
    uint32_t out = 0;
    for (int sh = 0; sh <= 16; sh += 8) {
        const uint32_t ca = (a >> sh) & 0xFF, cb = (b >> sh) & 0xFF;
        out |= ((ca * (255 - t) + cb * t + 127) / 255) << sh;
    }
    return out;
}
inline uint32_t scaled(uint32_t c, uint32_t num, uint32_t den) {   // c * num / den per channel
    uint32_t out = 0;
    for (int sh = 0; sh <= 16; sh += 8) out |= ((((c >> sh) & 0xFF) * num / den) & 0xFF) << sh;
    return out;
}

uint32_t recolour(const Palette& p, uint32_t c) {
    if (c <= 1) return c;   // 0 / 1: the flag slots and black stay as they are
    const uint32_t r = (c >> 16) & 0xFF, g = (c >> 8) & 0xFF, b = c & 0xFF;
    switch (c) {
        case 0xCD1818: case 0xFF0000: case 0xDD2020: case 0xC64E4D: return p.accent;
        case 0x30CB3F: case 0x00FF00: return p.good;
        case 0x00E8BE: return p.note;
        case 0xFEF749: return p.instr;
        case 0xBB58F1: return p.fx1;
        case 0x57F1FF: return p.fx2;
        case 0x003933: return scaled(p.note, 1, 4);    // the column tints
        case 0x453B1B: return scaled(p.instr, 1, 4);
        case 0x321F3A: return scaled(p.fx1, 1, 4);
        case 0x183744: return scaled(p.fx2, 1, 4);
        case 0xD67022: return p.orange;
        case 0x3FFFFF: return p.cyan;
        default: break;
    }
    const int mx = r > g ? (r > b ? r : b) : (g > b ? g : b), mn = r < g ? (r < b ? r : b) : (g < b ? g : b);
    if (mx - mn <= 4) return mix(p.bg, p.text, uint32_t((r + g + b) / 3));   // a grey
    return c;
}

const Theme& theme(uint8_t index) {
    if (index < kThemeCount) return themes()[index];
    if (index >= kThemeTotal) return themes()[0];
    // One derived theme is built at a time (the active one), in RAM.
    static uint32_t slots[kThemeSlotCount];
    static Theme t{};
    static uint8_t built = 0xFF, builtPhase = 0;
    if (built != index || (kPalettes[index - kThemeCount].anim && builtPhase != gAnimPhase)) {
        Palette p = kPalettes[index - kThemeCount];
        if (p.anim == 1) {          // Cyber Pulse: the accent breathes between pink and cyan
            const uint32_t t = gAnimPhase < 128 ? gAnimPhase * 2u : (255u - gAnimPhase) * 2u;
            p.accent = mix(p.accent, p.cyan, t > 255 ? 255 : t);
            p.good = mix(p.good, 0xFF2E88, t > 255 ? 255 : t);   // the cursor breathes too
        } else if (p.anim == 2) {   // Spectrum: the accent hue turns
            const uint32_t h = gAnimPhase * 6u;   // 0..1530
            const uint32_t seg = h / 256u, f = h % 256u;
            static const uint32_t kKeys[7] = {0xFF3040, 0xFFE040, 0x40FF80, 0x40E0FF, 0x5060FF, 0xFF40E0, 0xFF3040};
            p.accent = mix(kKeys[seg > 5 ? 5 : seg], kKeys[seg > 5 ? 6 : seg + 1], f);
            p.good = mix(kKeys[(seg + 2) % 6], kKeys[(seg + 3) % 6], f);
        } else if (p.anim == 3) {   // Acid House: the accent pumps yellow -> pink on the beat
            const uint32_t t = gAnimPhase < 64 ? 255u - gAnimPhase * 4u : 0u;   // a sharp attack, a decay
            p.accent = mix(0xFF3D9A, 0xFFE600, t);
            p.good = mix(0x00F0FF, 0x9DFF00, t);
        } else if (p.anim == 4) {   // Plasma: the background drifts purple -> blue -> teal
            static const uint32_t kBg[4] = {0x12051E, 0x05102A, 0x041C1C, 0x12051E};
            const uint32_t h = gAnimPhase * 3u, seg = h / 256u, f = h % 256u;
            p.bg = mix(kBg[seg > 2 ? 2 : seg], kBg[seg > 2 ? 3 : seg + 1], f);
            p.accent = mix(0xFF4FD8, 0x4DE3FF, gAnimPhase < 128 ? gAnimPhase * 2u : (255u - gAnimPhase) * 2u);
        } else if (p.anim == 5) {   // Colour Wheel: the four column colours rotate
            static const uint32_t kCols[4] = {0x40FF90, 0xFFE040, 0xC070FF, 0x60FFD8};
            const uint32_t h = gAnimPhase * 4u, seg = h / 256u, f = h % 256u;
            p.note = mix(kCols[seg % 4], kCols[(seg + 1) % 4], f);
            p.instr = mix(kCols[(seg + 1) % 4], kCols[(seg + 2) % 4], f);
            p.fx1 = mix(kCols[(seg + 2) % 4], kCols[(seg + 3) % 4], f);
            p.fx2 = mix(kCols[(seg + 3) % 4], kCols[seg % 4], f);
        } else if (p.anim == 6) {   // Ember: the accent and the cursor flicker like a fire
            const uint32_t n = (gAnimPhase * 2654435761u) >> 24;   // a cheap hash of the phase
            p.accent = mix(0xFF2A00, 0xFFB000, (n * 3u) & 255u);
            p.good = mix(0xFF8A3D, 0xFFE0A0, (n * 7u) & 255u);
        } else if (p.anim == 7) {   // Night Drive: the background pulses with the "sun" colour
            const uint32_t t = gAnimPhase < 128 ? gAnimPhase * 2u : (255u - gAnimPhase) * 2u;
            p.bg = mix(0x0A0418, 0x22062E, t);
            p.accent = mix(0xFF2A6D, 0xFF9E00, t);
        } else if (p.anim == 8) {   // Glitch: rare short flashes of colour on a datamatic page
            const uint32_t n = (gAnimPhase * 2246822519u) >> 26;   // 0..63
            if (n < 3) {
                p.accent = n == 0 ? 0xFF0040 : (n == 1 ? 0x00FFE0 : 0xFFFF00);
                p.note = 0x00FFE0;
                p.fx1 = 0xFF0040;
            }
        }
        builtPhase = gAnimPhase;
        const uint32_t* base = themes()[p.base].slots;
        for (int i = 0; i < kThemeSlotCount; ++i)
            slots[i] = i >= slot::kFlagBottomFade ? base[i] : recolour(p, base[i]);
        // Black frame clear / list backgrounds take the palette background.
        if (base[slot::kFrameClear] == 0) slots[slot::kFrameClear] = p.bg;
        t = makeTheme(p.name, slots);
        built = index;
    }
    return t;
}

bool themeAnimated(uint8_t index) {
    return index >= kThemeCount && index < kThemeTotal && kPalettes[index - kThemeCount].anim != 0;
}

void themeTick(uint8_t index, uint32_t ms) {
    if (!themeAnimated(index)) return;
    // Cyber Pulse: one breath in about 4 s; Spectrum: a turn in about 12 s;
    // Acid House a 120 BPM beat; Plasma 20 s; Colour Wheel 16 s; Ember fast;
    // Night Drive 6 s; Glitch 2 s.
    static const uint32_t kPeriod[9] = {12000u, 4000u, 12000u, 500u, 20000u, 16000u, 1500u, 6000u, 2000u};
    const uint8_t an = kPalettes[index - kThemeCount].anim;
    const uint32_t period = kPeriod[an < 9 ? an : 0];
    gAnimPhase = uint8_t((ms % period) * 256u / period);
}

uint32_t themeTickMs(uint8_t index) {
    if (!themeAnimated(index)) return 125;
    const uint8_t an = kPalettes[index - kThemeCount].anim;
    return an == 3 || an == 8 || an == 6 ? 60u : 125u;
}

const char* themeName(uint8_t index) {
    if (index < kThemeCount) return themes()[index].name;
    return index < kThemeTotal ? kPalettes[index - kThemeCount].name : themes()[0].name;
}

uint8_t themeBase(uint8_t index) {
    if (index < kThemeCount) return index;
    return index < kThemeTotal ? kPalettes[index - kThemeCount].base : 0;
}

const char* fontSetName(uint8_t set) { return set == kFontSetNew ? "New" : (set == kFontSetPixel ? "Pixel" : "Original"); }

